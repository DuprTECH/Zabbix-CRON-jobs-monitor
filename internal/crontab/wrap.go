package crontab

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// WrapOptions control how a cron line is rewritten.
type WrapOptions struct {
	Wrapper string // path of zbxntfy to insert, e.g. /usr/bin/zbxntfy
	Notify  string // optional value for "-t"
}

var safeArg = regexp.MustCompile(`^[A-Za-z0-9_./-]+$`)

// PlanWrap returns the job's line with zbxntfy inserted in front of the
// command. The new line is parsed again and must be recognized as the same,
// now monitored job.
func PlanWrap(j Job, o WrapOptions) (string, error) {
	if j.Monitored == 1 {
		return "", errors.New("already monitored")
	}
	if j.insertAt < 0 || j.insertAt > len(j.rawLine) {
		return "", errors.New("cannot find the command in the line")
	}
	if !safeArg.MatchString(o.Wrapper) {
		return "", fmt.Errorf("unsupported wrapper path %q", o.Wrapper)
	}
	ins := o.Wrapper
	if j.Name != j.baseName {
		ins += " -n " + j.Name // keep the de-duplicated name
	}
	if o.Notify != "" {
		if !safeArg.MatchString(o.Notify) {
			return "", fmt.Errorf("-t value %q may contain only A-Z a-z 0-9 _ . / -", o.Notify)
		}
		ins += " -t " + o.Notify
	}
	newLine := j.rawLine[:j.insertAt] + ins + " " + j.rawLine[j.insertAt:]

	nj, err := parseLine(strings.TrimSpace(newLine), j.SystemCrontab(), j.User)
	if err != nil {
		return "", fmt.Errorf("rewritten line does not parse: %v", err)
	}
	if nj.Monitored != 1 || nj.Name != j.Name {
		return "", fmt.Errorf("rewritten line is not recognized as monitored job %q", j.Name)
	}
	return newLine, nil
}

// Edit is one line change.
type Edit struct {
	Job     Job
	NewLine string
}

// Applier writes edits to crontabs.
type Applier struct {
	BackupDir string
	// InstallUserCrontab installs content as the crontab of user
	// (normally "crontab -u <user> -"); user crontabs are never written directly
	// so that cron reliably reloads them.
	InstallUserCrontab func(user, content string) error
}

// Result describes what happened to one crontab file.
type Result struct {
	File    string
	Backup  string
	Restore string // shell command that restores the backup
	Edits   int
	Err     error
}

// Apply backs up every affected crontab and then writes the edits, file by
// file. A file whose content changed since it was scanned is skipped.
func (a Applier) Apply(edits []Edit) []Result {
	byFile := map[string][]Edit{}
	var files []string
	for _, e := range edits {
		f := e.Job.file
		if _, ok := byFile[f]; !ok {
			files = append(files, f)
		}
		byFile[f] = append(byFile[f], e)
	}
	sort.Strings(files)

	var res []Result
	for _, f := range files {
		r := Result{File: f, Edits: len(byFile[f])}
		r.Err = a.applyFile(f, byFile[f], &r)
		res = append(res, r)
	}
	return res
}

var debianHeader = regexp.MustCompile(`^# (DO NOT EDIT THIS FILE|\(.* installed on |\(Cron version )`)

func (a Applier) applyFile(file string, edits []Edit, r *Result) error {
	orig, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	lines := strings.SplitAfter(string(orig), "\n")
	for _, e := range edits {
		i := e.Job.lineNo - 1
		if i < 0 || i >= len(lines) {
			return fmt.Errorf("line %d not found, file changed since scan", e.Job.lineNo)
		}
		cur := strings.TrimRight(lines[i], "\r\n")
		if cur != e.Job.rawLine {
			return fmt.Errorf("line %d changed since scan", e.Job.lineNo)
		}
		lines[i] = e.NewLine + lines[i][len(cur):] // keep the line ending
	}
	content := strings.Join(lines, "")

	// backup first
	rel := strings.TrimPrefix(file, filepath.VolumeName(file))
	r.Backup = filepath.Join(a.BackupDir, strings.TrimLeft(filepath.ToSlash(rel), "/"))
	if err := os.MkdirAll(filepath.Dir(r.Backup), 0o700); err != nil {
		return fmt.Errorf("backup: %v", err)
	}
	if err := os.WriteFile(r.Backup, orig, 0o600); err != nil {
		return fmt.Errorf("backup: %v", err)
	}

	if edits[0].Job.SystemCrontab() {
		r.Restore = fmt.Sprintf("cp -p %s %s", r.Backup, file)
		return replaceFile(file, content)
	}
	user := edits[0].Job.User
	r.Restore = fmt.Sprintf("crontab -u %s %s", user, r.Backup)
	if a.InstallUserCrontab == nil {
		return errors.New("no way to install user crontabs")
	}
	return a.InstallUserCrontab(user, stripHeader(content))
}

// stripHeader removes the "DO NOT EDIT" header Debian's crontab(1) adds, so it
// is not duplicated when the content is installed again.
func stripHeader(s string) string {
	lines := strings.SplitAfter(s, "\n")
	i := 0
	for i < len(lines) && i < 3 && debianHeader.MatchString(lines[i]) {
		i++
	}
	return strings.Join(lines[i:], "")
}

// replaceFile atomically replaces file, keeping its mode and owner. The
// temporary file starts with a dot so cron ignores it.
func replaceFile(file, content string) error {
	st, err := os.Stat(file)
	if err != nil {
		return err
	}
	tmp := filepath.Join(filepath.Dir(file), ".zbxntfy-wrap."+filepath.Base(file)+".tmp")
	if err := os.WriteFile(tmp, []byte(content), st.Mode().Perm()); err != nil {
		return err
	}
	if err := os.Chmod(tmp, st.Mode().Perm()); err != nil {
		os.Remove(tmp)
		return err
	}
	if err := copyOwner(st, tmp); err != nil {
		os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, file); err != nil {
		os.Remove(tmp)
		return err
	}
	return nil
}
