func wrapFixture(t *testing.T) (string, map[string]Job) {
	t.Helper()
	root := t.TempDir()
	write(t, root, "etc/crontab", "SHELL=/bin/sh\n"+
		"17 *\t* * *\troot    cd / && run-parts --report /etc/cron.hourly\n"+
		"25 6\t* * *\troot\ttest -x /usr/sbin/anacron || { cd / && run-parts --report /etc/cron.daily; }\n")
	write(t, root, "etc/cron.d/php", "09,39 *     * * *     root   [ -x /usr/lib/php/sessionclean ] && if [ ! -d /run/systemd/system ]; then /usr/lib/php/sessionclean; fi\n")
	write(t, root, "var/spool/cron/crontabs/root", "# DO NOT EDIT THIS FILE - edit the master and reinstall.\n"+
		"# (/tmp/crontab.x installed on Thu Nov  5 10:00:00 2026)\n"+
		"# (Cron version -- $Id: crontab.c,v 2.13 1994/01/17 03:20:37 vixie Exp $)\n"+
		"40 2 * * * /opt/./zabbix-dump -q\r\n"+
		"  20 0 * * * ZBX_KEY=abc python3 /root/zabbix/suppress_longdown.py --apply >/dev/null 2>&1\n"+
		"0 4 * * * date +\\%F%stdin\n"+
		"0 5 * * * /opt/backup.sh --db\n"+
		"0 6 * * * /opt/backup.sh --files\n"+
		"0 7 * * * zbxntfy /opt/ok.sh\n")
	jobs, errs := Scanner{Root: root}.Scan()
	if len(errs) != 0 {
		t.Fatalf("errs: %q", errs)
	}
	m := map[string]Job{}
	for _, j := range jobs {
		m[j.Name] = j
	}
	return root, m
}

func TestPlanWrap(t *testing.T) {
	_, jobs := wrapFixture(t)
	o := WrapOptions{Wrapper: "/usr/bin/zbxntfy"}
	cases := map[string]string{
		"cron.hourly":       "17 *\t* * *\troot    cd / && /usr/bin/zbxntfy run-parts --report /etc/cron.hourly",
		"cron.daily":        "25 6\t* * *\troot\ttest -x /usr/sbin/anacron || { cd / && /usr/bin/zbxntfy run-parts --report /etc/cron.daily; }",
		"sessionclean":      "09,39 *     * * *     root   [ -x /usr/lib/php/sessionclean ] && if [ ! -d /run/systemd/system ]; then /usr/bin/zbxntfy /usr/lib/php/sessionclean; fi",
		"zabbix-dump":       "40 2 * * * /usr/bin/zbxntfy /opt/./zabbix-dump -q",
		"suppress_longdown": "  20 0 * * * ZBX_KEY=abc /usr/bin/zbxntfy python3 /root/zabbix/suppress_longdown.py --apply >/dev/null 2>&1",
		"date":              "0 4 * * * /usr/bin/zbxntfy date +\\%F%stdin",
		"backup":            "0 5 * * * /usr/bin/zbxntfy /opt/backup.sh --db",
		"backup-2":          "0 6 * * * /usr/bin/zbxntfy -n backup-2 /opt/backup.sh --files",
	}
	for name, want := range cases {
		j, ok := jobs[name]
		if !ok {
			t.Errorf("job %q not found", name)
			continue
		}
		got, err := PlanWrap(j, o)
		if err != nil || got != want {
			t.Errorf("%s:\n got %q (%v)\nwant %q", name, got, err, want)
		}
	}
	if _, err := PlanWrap(jobs["ok"], o); err == nil {
		t.Error("monitored job must not be wrapped again")
	}
	got, err := PlanWrap(jobs["zabbix-dump"], WrapOptions{Wrapper: "zbxntfy", Notify: "IT_ops"})
	if err != nil || got != "40 2 * * * zbxntfy -t IT_ops /opt/./zabbix-dump -q" {
		t.Errorf("notify: %q %v", got, err)
	}
	if _, err := PlanWrap(jobs["zabbix-dump"], WrapOptions{Wrapper: "zbxntfy", Notify: "a;rm -rf"}); err == nil {
		t.Error("unsafe -t value accepted")
	}
}

func TestApply(t *testing.T) {
	root, jobs := wrapFixture(t)
	o := WrapOptions{Wrapper: "zbxntfy"}
	var edits []Edit
	for _, n := range []string{"cron.hourly", "zabbix-dump", "suppress_longdown"} {
		nl, err := PlanWrap(jobs[n], o)
		if err != nil {
			t.Fatal(err)
		}
		edits = append(edits, Edit{Job: jobs[n], NewLine: nl})
	}
	var installed map[string]string = map[string]string{}
	a := Applier{
		BackupDir: filepath.Join(root, "backup"),
		InstallUserCrontab: func(user, content string) error {
			installed[user] = content
			return nil
		},
	}
	for _, r := range a.Apply(edits) {
		if r.Err != nil {
			t.Fatalf("%s: %v", r.File, r.Err)
		}
		if _, err := os.Stat(r.Backup); err != nil {
			t.Errorf("no backup for %s", r.File)
		}
	}

	sys, _ := os.ReadFile(filepath.Join(root, "etc/crontab"))
	if !strings.Contains(string(sys), "cd / && zbxntfy run-parts --report /etc/cron.hourly\n") ||
		!strings.Contains(string(sys), "{ cd / && run-parts --report /etc/cron.daily; }") {
		t.Errorf("etc/crontab:\n%s", sys)
	}
	src := filepath.Join(root, "etc/crontab")
	bak, _ := os.ReadFile(filepath.Join(root, "backup", strings.TrimLeft(filepath.ToSlash(strings.TrimPrefix(src, filepath.VolumeName(src))), "/")))
	if strings.Contains(string(bak), "zbxntfy") {
		t.Error("backup must contain the original file")
	}
	u := installed["root"]
	want := "40 2 * * * zbxntfy /opt/./zabbix-dump -q\r\n" +
		"  20 0 * * * ZBX_KEY=abc zbxntfy python3 /root/zabbix/suppress_longdown.py --apply >/dev/null 2>&1\n"
	if !strings.HasPrefix(u, want) || strings.Contains(u, "DO NOT EDIT") {
		t.Errorf("user crontab:\n%q", u)
	}

	// re-scan: applied jobs are monitored now, with the same names
	jobs2, _ := Scanner{Root: root}.Scan()
	for _, j := range jobs2 {
		if j.Name == "cron.hourly" && j.Monitored != 1 {
			t.Error("cron.hourly not monitored after apply")
		}
	}

	// a stale edit (file changed in the meantime) is refused
	res := a.Apply(edits[:1])
	if res[0].Err == nil {
		t.Error("stale edit applied")
	}
}
